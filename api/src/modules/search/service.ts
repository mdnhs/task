import { sql } from "drizzle-orm"
import type { Module } from "@opsdesk/domain/permissions"
import { AppError } from "../../core/errors"
import type { TenantTx } from "../../db/tenant-tx"

export const DEFAULT_LIMIT = 10
export const MAX_LIMIT = 20
export const MIN_Q = 2
export const MAX_Q = 100
const MAX_TOKENS = 8
const MAX_TOKEN_LEN = 40
/** pg_trgm word-similarity floor for the typo fallback (default 0.6 is too strict for one-letter slips). */
const TRGM_THRESHOLD = "0.3"

export const InvalidQuery = () => new AppError(422, "invalid_query", "Unprocessable Entity")

export type SearchDoc = { tenantId: string; entity: string; entityId: string; module: Module; title: string; body: string }
export type SearchHit = { entity: string; entityId: string; title: string; module: string }

/** Inserts or replaces the document for (tenant, entity, id). tsv is generated by the database. */
export async function indexDocument(tx: TenantTx, doc: SearchDoc, now: Date): Promise<void> {
  await tx.execute(sql`
    insert into search_documents (tenant_id, entity, entity_id, module, title, body, updated_at)
    values (${doc.tenantId}, ${doc.entity}, ${doc.entityId}, ${doc.module}, ${doc.title}, ${doc.body}, ${now})
    on conflict (tenant_id, entity, entity_id)
    do update set module = excluded.module, title = excluded.title, body = excluded.body, updated_at = excluded.updated_at`)
}

export async function removeDocument(tx: TenantTx, tenantId: string, entity: string, entityId: string): Promise<void> {
  await tx.execute(sql`delete from search_documents where tenant_id = ${tenantId} and entity = ${entity} and entity_id = ${entityId}`)
}

/** GDPR erase: the user's member document and the documents of files they own (names can identify a person). */
export async function removeDocumentsForUser(tx: TenantTx, tenantId: string, userId: string): Promise<void> {
  await tx.execute(sql`
    delete from search_documents where tenant_id = ${tenantId} and (
      (entity = 'member' and entity_id = ${userId})
      or (entity = 'file' and entity_id in (select id::text from files where tenant_id = ${tenantId} and owner_user_id = ${userId})))`)
}

/**
 * Validates the raw q (trimmed length 2..100, else 422 invalid_query) and reduces it to word tokens: lower-cased runs
 * of letters/digits only. Nothing else survives, so no tsquery operator or quote can reach to_tsquery.
 */
export function parseQuery(raw: string | undefined): { tokens: string[]; text: string } {
  const q = (raw ?? "").trim()
  if (q.length < MIN_Q || q.length > MAX_Q) throw InvalidQuery()
  const tokens = q.toLowerCase().split(/[^\p{L}\p{N}]+/u).filter(Boolean).map((t) => t.slice(0, MAX_TOKEN_LEN)).slice(0, MAX_TOKENS)
  return { tokens, text: tokens.join(" ") }
}

export function parseLimit(raw: string | undefined): number {
  const n = Number.parseInt(raw ?? "", 10)
  if (!Number.isFinite(n)) return DEFAULT_LIMIT
  return Math.min(MAX_LIMIT, Math.max(1, n))
}

/**
 * Hits among `modules`: every token must match (the last as a prefix, `tok:*`), OR the title is trigram-similar to the
 * query (typos). Ranked by ts_rank + word_similarity. The tenant filter is explicit on top of forced RLS.
 */
export async function searchDocuments(tx: TenantTx, tenantId: string, modules: Module[], rawQ: string | undefined, limit: number): Promise<SearchHit[]> {
  const { tokens, text } = parseQuery(rawQ)
  if (tokens.length === 0 || modules.length === 0) return []
  const tsq = tokens.map((t, i) => (i === tokens.length - 1 ? `${t}:*` : t)).join(" & ")
  await tx.execute(sql`select set_config('pg_trgm.word_similarity_threshold', ${TRGM_THRESHOLD}, true)`)
  const res = await tx.execute(sql`
    select entity, entity_id, title, module,
      ts_rank(tsv, to_tsquery('simple', ${tsq})) + word_similarity(${text}, lower(title)) as score
    from search_documents
    where tenant_id = ${tenantId}
      and module = any(${sql.raw("ARRAY[")}${sql.join(modules.map((m) => sql`${m}`), sql`, `)}${sql.raw("]::text[]")})
      and (tsv @@ to_tsquery('simple', ${tsq}) or ${text} <% lower(title))
    order by score desc, title asc, entity_id asc
    limit ${limit}`)
  return (res.rows as { entity: string; entity_id: string; title: string; module: string }[]).map((r) => ({ entity: r.entity, entityId: r.entity_id, title: r.title, module: r.module }))
}
